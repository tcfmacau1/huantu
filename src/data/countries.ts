import type { MetricId } from "@/data/metrics";

export type CountryRow = {
  key: string;
  zh: string;
  region: string;
  values: Record<MetricId, number | null>;
};

function num(raw: string, key: string, field: string): number | null {
  if (raw === "-") return null;
  const value = Number(raw);
  if (!Number.isFinite(value)) throw new Error(`Bad ${field} for ${key}: ${raw}`);
  return value;
}

function parse(table: string): CountryRow[] {
  return table
    .trim()
    .split("\n")
    .map((line) => {
      const [key, zh, region, hdi, life, gdp, net, renew, co2] = line.split("|").map((part) => part.trim());
      return {
        key,
        zh,
        region,
        values: {
          hdi: num(hdi, key, "hdi"),
          life: num(life, key, "life"),
          gdp: num(gdp, key, "gdp"),
          net: num(net, key, "net"),
          renew: num(renew, key, "renew"),
          co2: num(co2, key, "co2"),
        },
      };
    });
}

